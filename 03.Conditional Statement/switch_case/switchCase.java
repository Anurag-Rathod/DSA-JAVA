public class switchCase {
    public static void main(String args[]){
        int number = 2;
        switch(number){
            case 1 : System.out.print("samosa");
                     break;
            case 2 : System.out.print("burger");
                     break;  
            case 3 : System.out.print("apple");
                     break; 
            default : System.out.print("mango");
        }

        char ch = 'a';
        switch(ch){
            case 'd' : System.out.print("samosa");
                     break;
            case 'e' : System.out.print("burger");
                     break;  
            case 'a' : System.out.print("apple");
                     break; 
            default : System.out.print("mango");
        }
    }
}
