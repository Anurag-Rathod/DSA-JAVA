public class type_Casting {
    public static void main(String[] args){
        char ch = 'A';
        int a = ch; //in java, type conversion (also known as type casting) is possible from char to int.
        System.out.println(a);

        float num = 10.1111f;
        int number = (int) num;
        System.out.print(number);

    }
}
