public class DataType {
    public static void main(String[] args){
        byte b = 9; // Range of byte is -128 to 127
        System.out.println(b);

        char ch = 'A';
        System.out.println(ch); // Prints the character 'A'

        int num = 1;
        System.out.println(num); // Prints the number 1

        //float pi = 3.14; In Java, literals like 3.14 are considered double by default, and you cannot directly assign a double value to a float without explicitly casting or marking the value as a float.

        float pi = 3.14f; // Use 'f' to indicate that it's a float, not a double
        System.out.println(pi); // Prints the value of pi

        //boolean flag = true; 
        //short s = 20000; Short range: -32768 to 32767
        //double d = 3.14159265359;
        //long l = 123456789012L;

    }
}
